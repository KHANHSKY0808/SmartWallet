import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const feRoot = path.resolve(__dirname, '..');
const openapiDir = path.join(feRoot, 'src', 'app', 'core', 'api', 'openapi');
const outDir = path.join(feRoot, 'src', 'app', 'core', 'api', 'generated');
const cliPath = path.join(feRoot, 'node_modules', 'openapi-typescript', 'bin', 'cli.js');

if (!fs.existsSync(openapiDir)) {
  throw new Error(`OpenAPI directory not found: ${openapiDir}`);
}
if (!fs.existsSync(cliPath)) {
  throw new Error(`openapi-typescript CLI not found at ${cliPath}`);
}

fs.mkdirSync(outDir, { recursive: true });
const files = fs.readdirSync(openapiDir).filter(f => f.endsWith('.json')).sort();
if (files.length === 0) {
  throw new Error(`No .json OpenAPI files found in ${openapiDir}`);
}

const exportsLines = ['/* Auto-generated by tools/generate-api-types.mjs (D74). Do not edit manually. */'];

for (const file of files) {
  const name = file.replace(/\.json$/, '');
  const pascal = name
    .split('-')
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
  const inPath = path.join(openapiDir, file);
  const outPath = path.join(outDir, `${name}.ts`);

  execFileSync(process.execPath, [cliPath, inPath, '-o', outPath], {
    cwd: feRoot,
    stdio: 'inherit',
  });

  const content = fs.readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n');
  fs.writeFileSync(outPath, content, 'utf8');
  exportsLines.push(`export type { components as ${pascal}Components, paths as ${pascal}Paths } from './${name}';`);
}

fs.writeFileSync(path.join(outDir, 'index.ts'), exportsLines.join('\n') + '\n', 'utf8');
console.log(`Generated ${files.length} OpenAPI TypeScript contract files in ${outDir}`);

